// NewChatCompletionResponse creates a new ChatCompletionResponse.
func NewChatCompletionResponse(id, model string, message ChatMessage, finishReason string, usage *Usage) *ChatCompletionResponse {
	reason := finishReason
	return &ChatCompletionResponse{
		ID:      id,
		Object:  "chat.completion",
		Created: time.Now().Unix(),
		Model:   model,
		Choices: []ChatCompletionChoice{
			{
				Index:        0,
				Message:      message,
				FinishReason: &reason,
			},
		},
		Usage: usage,
	}
}

// NewChatCompletionChunk creates a new streaming chunk.
func NewChatCompletionChunk(id, model string, delta ChatMessageDelta, finishReason *string) *ChatCompletionChunk {
	return &ChatCompletionChunk{
		ID:      id,
		Object:  "chat.completion.chunk",
		Created: time.Now().Unix(),
		Model:   model,
		Choices: []ChatCompletionChunkChoice{
			{
				Index:        0,
				Delta:        delta,
				FinishReason: finishReason,
			},
		},
	}
}
