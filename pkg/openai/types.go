// ChatCompletionRequest represents a request to the /v1/chat/completions endpoint.
type ChatCompletionRequest struct {
	// Model is the ID of the model to use. Use "auto" for automatic routing.
	Model string `json:"model"`

	// Messages is a list of messages comprising the conversation so far.
	Messages []ChatMessage `json:"messages"`

	// Temperature controls randomness. Lower values make responses more deterministic.
	// Range: 0.0 to 2.0. Default: 1.0
	Temperature *float64 `json:"temperature,omitempty"`

	// TopP is an alternative to temperature for nucleus sampling.
	// Range: 0.0 to 1.0. Default: 1.0
	TopP *float64 `json:"top_p,omitempty"`

	// N is the number of chat completion choices to generate.
	// Default: 1
	N *int `json:"n,omitempty"`

	// Stream enables server-sent events for streaming responses.
	// Default: false
	Stream bool `json:"stream,omitempty"`

	// Stop sequences where the API will stop generating further tokens.
	Stop []string `json:"stop,omitempty"`

	// MaxTokens is the maximum number of tokens to generate.
	MaxTokens *int `json:"max_tokens,omitempty"`

	// PresencePenalty penalizes new tokens based on whether they appear in the text so far.
	// Range: -2.0 to 2.0. Default: 0
	PresencePenalty *float64 `json:"presence_penalty,omitempty"`

	// FrequencyPenalty penalizes new tokens based on their existing frequency.
	// Range: -2.0 to 2.0. Default: 0
	FrequencyPenalty *float64 `json:"frequency_penalty,omitempty"`

	// LogitBias modifies the likelihood of specified tokens appearing.
	LogitBias map[string]float64 `json:"logit_bias,omitempty"`

	// User is a unique identifier representing your end-user.
	User string `json:"user,omitempty"`

	// ResponseFormat specifies the format of the response.
	ResponseFormat *ResponseFormat `json:"response_format,omitempty"`

	// Seed for deterministic sampling (beta).
	Seed *int `json:"seed,omitempty"`

	// Tools is a list of tools the model may call.
	Tools []Tool `json:"tools,omitempty"`

	// ToolChoice controls which tool is called by the model.
	ToolChoice interface{} `json:"tool_choice,omitempty"`
}

// ChatMessage represents a single message in a chat conversation.
type ChatMessage struct {
	// Role is the role of the message author: "system", "user", "assistant", or "tool".
	Role string `json:"role"`

	// Content is the contents of the message.
	Content string `json:"content"`

	// Name is an optional name for the participant (for multi-user chats).
	Name string `json:"name,omitempty"`

	// ToolCalls is the tool calls generated by the model.
	ToolCalls []ToolCall `json:"tool_calls,omitempty"`

	// ToolCallID is the ID of the tool call this message is responding to.
	ToolCallID string `json:"tool_call_id,omitempty"`
}

// UnmarshalJSON decodes a chat message, accepting the OpenAI `content` field in
// either of its two valid shapes: a plain string, or an array of content parts
// (e.g. [{"type":"text","text":"..."}, {"type":"image_url", ...}]). Text parts
// are concatenated (joined with newlines); non-text parts (such as image_url)
// are skipped because the backend models are text-only. This keeps the public
// Content field a flat string so all downstream consumers are unaffected.
func (m *ChatMessage) UnmarshalJSON(data []byte) error {
	// Alias avoids infinite recursion; Content captured raw for custom handling.
	type alias ChatMessage
	aux := &struct {
		Content json.RawMessage `json:"content"`
		*alias
	}{alias: (*alias)(m)}

	if err := json.Unmarshal(data, aux); err != nil {
		return err
	}

	m.Content = flattenContent(aux.Content)
	return nil
}

// flattenContent converts the raw JSON of an OpenAI message `content` field into
// a plain string. It accepts a JSON string, a JSON array of content parts, or
// null/absent (which yields an empty string).
func flattenContent(raw json.RawMessage) string {
	trimmed := bytes.TrimSpace(raw)
	if len(trimmed) == 0 || string(trimmed) == "null" {
		return ""
	}

	// Plain string content.
	if trimmed[0] == '"' {
		var s string
		if err := json.Unmarshal(trimmed, &s); err == nil {
			return s
		}
		return ""
	}

	// Array of content parts.
	if trimmed[0] == '[' {
		var parts []struct {
			Type string `json:"type"`
			Text string `json:"text"`
		}
		if err := json.Unmarshal(trimmed, &parts); err != nil {
			return ""
		}
		var texts []string
		for _, p := range parts {
			// Collect text parts; skip images and other non-text modalities.
			if p.Text != "" && (p.Type == "" || p.Type == "text") {
				texts = append(texts, p.Text)
			}
		}
		return strings.Join(texts, "\n")
	}

	return ""
}

// ChatCompletionResponse represents the response from /v1/chat/completions.
type ChatCompletionResponse struct {
	// ID is a unique identifier for this completion.
	ID string `json:"id"`

	// Object is always "chat.completion".
	Object string `json:"object"`

	// Created is the Unix timestamp of when the completion was created.
	Created int64 `json:"created"`

	// Model is the model used for the completion.
	Model string `json:"model"`

	// Choices is a list of chat completion choices.
	Choices []ChatCompletionChoice `json:"choices"`

	// Usage contains token usage information.
	Usage *Usage `json:"usage,omitempty"`

	// SystemFingerprint is a fingerprint of the system configuration.
	SystemFingerprint string `json:"system_fingerprint,omitempty"`
}

// ChatCompletionChoice represents a single completion choice.
type ChatCompletionChoice struct {
	// Index is the index of this choice in the list.
	Index int `json:"index"`

	// Message is the chat message generated by the model.
	Message ChatMessage `json:"message"`

	// FinishReason indicates why the model stopped generating tokens.
	// Values: "stop", "length", "tool_calls", "content_filter", or null.
	FinishReason *string `json:"finish_reason"`

	// LogProbs contains log probability information (if requested).
	LogProbs *LogProbs `json:"logprobs,omitempty"`
}

// ChatChoice is an alias for server compatibility (non-pointer finish reason).
type ChatChoice struct {
	Index        int         `json:"index"`
	Message      ChatMessage `json:"message"`
	FinishReason string      `json:"finish_reason"`
}

// ChatChunkChoice is a streaming chunk choice with non-pointer finish reason.
type ChatChunkChoice struct {
	Index        int       `json:"index"`
	Delta        ChatDelta `json:"delta"`
	FinishReason string    `json:"finish_reason,omitempty"`
}

// ChatDelta represents delta content in streaming.
type ChatDelta struct {
	Role    string `json:"role,omitempty"`
	Content string `json:"content,omitempty"`
}

// ChatCompletionChunk represents a single chunk in a streaming response.
type ChatCompletionChunk struct {
	// ID is a unique identifier for this completion.
	ID string `json:"id"`

	// Object is always "chat.completion.chunk".
	Object string `json:"object"`

	// Created is the Unix timestamp of when the chunk was created.
	Created int64 `json:"created"`

	// Model is the model used for the completion.
	Model string `json:"model"`

	// Choices contains the streamed choices.
	Choices []ChatCompletionChunkChoice `json:"choices"`

	// SystemFingerprint is a fingerprint of the system configuration.
	SystemFingerprint string `json:"system_fingerprint,omitempty"`
}

// ChatCompletionChunkChoice represents a single choice in a streaming chunk.
type ChatCompletionChunkChoice struct {
	// Index is the index of this choice.
	Index int `json:"index"`

	// Delta contains the streamed message delta.
	Delta ChatMessageDelta `json:"delta"`

	// FinishReason indicates why the model stopped (only in final chunk).
	FinishReason *string `json:"finish_reason"`

	// LogProbs contains log probability information (if requested).
	LogProbs *LogProbs `json:"logprobs,omitempty"`
}

// ChatMessageDelta represents the delta content in a streaming chunk.
type ChatMessageDelta struct {
	// Role is only present in the first chunk.
	Role string `json:"role,omitempty"`

	// Content is the delta content.
	Content string `json:"content,omitempty"`

	// ToolCalls are the delta tool calls.
	ToolCalls []ToolCallDelta `json:"tool_calls,omitempty"`
}

// Usage contains token usage information.
type Usage struct {
	// PromptTokens is the number of tokens in the prompt.
	PromptTokens int `json:"prompt_tokens"`

	// CompletionTokens is the number of tokens in the completion.
	CompletionTokens int `json:"completion_tokens"`

	// TotalTokens is the total number of tokens used.
	TotalTokens int `json:"total_tokens"`
}

// ResponseFormat specifies the format of the response.
type ResponseFormat struct {
	// Type is the response format type: "text" or "json_object".
	Type string `json:"type"`
}

// Tool represents a tool that the model may call.
type Tool struct {
	// Type is the type of tool (currently only "function").
	Type string `json:"type"`

	// Function contains the function definition.
	Function ToolFunction `json:"function"`
}

// ToolFunction describes a function that can be called.
type ToolFunction struct {
	// Name is the name of the function.
	Name string `json:"name"`

	// Description describes what the function does.
	Description string `json:"description,omitempty"`

	// Parameters is a JSON Schema object describing the function parameters.
	Parameters json.RawMessage `json:"parameters,omitempty"`
}

// ToolCall represents a tool call made by the model.
type ToolCall struct {
	// ID is the ID of the tool call.
	ID string `json:"id"`

	// Type is the type of tool call (currently only "function").
	Type string `json:"type"`

	// Function contains the function call details.
	Function ToolCallFunction `json:"function"`
}

// ToolCallFunction contains the details of a function call.
type ToolCallFunction struct {
	// Name is the name of the function to call.
	Name string `json:"name"`

	// Arguments is a JSON string of arguments to call the function with.
	Arguments string `json:"arguments"`
}

// ToolCallDelta represents a delta tool call in streaming.
type ToolCallDelta struct {
	// Index is the index of this tool call.
	Index int `json:"index"`

	// ID is the ID of the tool call (only in first chunk).
	ID string `json:"id,omitempty"`

	// Type is the type of tool call (only in first chunk).
	Type string `json:"type,omitempty"`

	// Function contains the delta function call.
	Function *ToolCallFunctionDelta `json:"function,omitempty"`
}

// ToolCallFunctionDelta contains delta function call details.
type ToolCallFunctionDelta struct {
	// Name is the function name (only in first chunk).
	Name string `json:"name,omitempty"`

	// Arguments is a delta of the arguments string.
	Arguments string `json:"arguments,omitempty"`
}

// LogProbs contains log probability information.
type LogProbs struct {
	// Content contains token log probabilities.
	Content []TokenLogProb `json:"content,omitempty"`
}

// TokenLogProb contains log probability for a single token.
type TokenLogProb struct {
	// Token is the token string.
	Token string `json:"token"`

	// LogProb is the log probability of this token.
	LogProb float64 `json:"logprob"`

	// Bytes is the UTF-8 bytes of the token.
	Bytes []int `json:"bytes,omitempty"`

	// TopLogProbs contains the most likely tokens.
	TopLogProbs []TopLogProb `json:"top_logprobs,omitempty"`
}

// TopLogProb contains a top log probability entry.
type TopLogProb struct {
	// Token is the token string.
	Token string `json:"token"`

	// LogProb is the log probability.
	LogProb float64 `json:"logprob"`

	// Bytes is the UTF-8 bytes of the token.
	Bytes []int `json:"bytes,omitempty"`
}

